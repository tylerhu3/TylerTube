// Cloudflare quick tunnel + Netlify redirect for the public TylerTube URL.
//
// A quick tunnel (`cloudflared tunnel --url http://localhost:8080`) gets a new random
// *.trycloudflare.com hostname on every start. This module finds (or starts) the tunnel for the
// Nginx port, reads its hostname from cloudflared's metrics server (GET /quicktunnel), and
// keeps github.com/tylerhu3/RedirectUrl (cloned at ./redirect-site, gitignored) pointing at it;
// Netlify rebuilds that repo on every push.
//
// Used by scripts/deploy-public.mjs (npm run deploy:public) and scripts/tunnel-watch.mjs
// (LaunchAgent com.tylertube.tunnel). CLI:
//   node scripts/tunnel.mjs status            show tunnels for the target + what's published
//   node scripts/tunnel.mjs ensure [--dry-run] find/start the tunnel, publish if it changed
import { execFile, spawn } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);
const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url));

export const config = {
  target: process.env.TUNNEL_TARGET || "http://localhost:8080",
  cloudflared: process.env.CLOUDFLARED || "cloudflared",
  // cloudflared's own default range is 20241-20245; ours is outside it to avoid clashes.
  metricsPort: Number(process.env.TUNNEL_METRICS_PORT) || 20250,
  logFile: process.env.TUNNEL_LOG || "/tmp/tylertube-cloudflared.log",
  redirectDir: process.env.REDIRECT_REPO_DIR || path.join(REPO_ROOT, "redirect-site"),
  redirectRepo: process.env.REDIRECT_REPO_URL || "https://github.com/tylerhu3/RedirectUrl.git",
  redirectBranch: process.env.REDIRECT_BRANCH || "main"
};

const LOOPBACK_HOSTS = new Set(["localhost", "127.0.0.1", "[::1]", "::1", "0.0.0.0"]);

export function log(...args) {
  console.log(`[tunnel ${new Date().toISOString()}]`, ...args);
}

// ---------- pure helpers (tested in tests/tunnel.test.js) ----------

function parseTarget(url) {
  try {
    const u = new URL(url);
    return { host: u.hostname, port: u.port || (u.protocol === "https:" ? "443" : "80") };
  } catch {
    return null;
  }
}

// Same port and both loopback → same origin as far as the tunnel is concerned.
export function targetsMatch(a, b) {
  const x = parseTarget(a);
  const y = parseTarget(b);
  if (!x || !y || x.port !== y.port) return false;
  return x.host === y.host || (LOOPBACK_HOSTS.has(x.host) && LOOPBACK_HOSTS.has(y.host));
}

function argValue(args, name) {
  for (let i = 0; i < args.length; i++) {
    if (args[i] === name) return args[i + 1];
    if (args[i].startsWith(`${name}=`)) return args[i].slice(name.length + 1);
  }
  return undefined;
}

// `ps -axo pid=,args=` output → quick-tunnel processes ({ pid, target, metrics? }).
// Named tunnels (`tunnel run …`) have no --url and are ignored.
export function parseQuickTunnelProcesses(psOutput) {
  const found = [];
  for (const line of psOutput.split("\n")) {
    const m = line.trim().match(/^(\d+)\s+(.*)$/);
    if (!m) continue;
    const args = m[2].split(/\s+/);
    if (!path.basename(args[0]).startsWith("cloudflared") || !args.includes("tunnel")) continue;
    const target = argValue(args, "--url");
    if (!target) continue;
    found.push({ pid: Number(m[1]), target, metrics: argValue(args, "--metrics") });
  }
  return found;
}

// `lsof -Fn` output → listening ports.
export function parseLsofPorts(lsofOutput) {
  const ports = [];
  for (const line of lsofOutput.split("\n")) {
    const m = line.match(/^n.*:(\d+)$/);
    if (m) ports.push(Number(m[1]));
  }
  return [...new Set(ports)];
}

export function renderRedirects(url) {
  return [
    "# Generated by TylerTube scripts/tunnel.mjs. Do not edit by hand.",
    "# 302 (not 301: browsers cache those forever); ! = also over existing files like index.html.",
    `/*  ${url}/:splat  302!`,
    ""
  ].join("\n");
}

export function renderIndexHtml(url) {
  // Only seen if the _redirects rule isn't applied (e.g. a local preview of the repo).
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url=${url}/">
<title>TylerTube</title>
</head>
<body style="font-family: system-ui, sans-serif; padding: 16px">
<p>Redirecting to <a href="${url}/">TylerTube</a>…</p>
</body>
</html>
`;
}

export function parsePublishedUrl(redirectsText) {
  const m = redirectsText.match(/^\/\*\s+(https:\/\/\S+?)\/:splat\b/m);
  return m ? m[1] : null;
}

// ---------- cloudflared ----------

async function fetchWithTimeout(url, ms = 2000, init = {}) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), ms);
  try {
    return await fetch(url, { ...init, signal: controller.signal, redirect: "manual" });
  } finally {
    clearTimeout(timer);
  }
}

async function metricsHostname(metricsAddr) {
  try {
    const res = await fetchWithTimeout(`http://${metricsAddr}/quicktunnel`, 1500);
    if (!res.ok) return null;
    const { hostname } = await res.json();
    return hostname || null;
  } catch {
    return null;
  }
}

export async function metricsReady(metricsAddr) {
  try {
    const res = await fetchWithTimeout(`http://${metricsAddr}/ready`, 1500);
    await res.text();
    return res.ok;
  } catch {
    return false;
  }
}

async function listeningPorts(pid) {
  try {
    const { stdout } = await run("lsof", ["-nP", "-a", "-p", String(pid), "-iTCP", "-sTCP:LISTEN", "-Fn"]);
    return parseLsofPorts(stdout);
  } catch {
    return [];
  }
}

// All running quick tunnels pointing at config.target, with their public URL when known.
export async function findTunnels() {
  const { stdout } = await run("ps", ["-axo", "pid=,args="]);
  const procs = parseQuickTunnelProcesses(stdout).filter((p) => targetsMatch(p.target, config.target));
  const tunnels = [];
  for (const proc of procs) {
    const candidates = proc.metrics
      ? [proc.metrics.includes(":") ? proc.metrics : `127.0.0.1:${proc.metrics}`]
      : (await listeningPorts(proc.pid)).map((port) => `127.0.0.1:${port}`);
    let hostname = null;
    let metrics = null;
    for (const addr of candidates) {
      hostname = await metricsHostname(addr);
      if (hostname) {
        metrics = addr;
        break;
      }
    }
    tunnels.push({ ...proc, metrics, url: hostname ? `https://${hostname}` : null });
  }
  return tunnels;
}

export async function startTunnel() {
  const metrics = `127.0.0.1:${config.metricsPort}`;
  const out = fs.openSync(config.logFile, "a");
  const child = spawn(
    config.cloudflared,
    ["tunnel", "--no-autoupdate", "--url", config.target, "--metrics", metrics],
    { detached: true, stdio: ["ignore", out, out] } // outlives this process
  );
  fs.closeSync(out);
  await new Promise((resolve, reject) => {
    child.once("spawn", resolve);
    child.once("error", reject);
  });
  child.unref();
  log(`started cloudflared pid ${child.pid} (log: ${config.logFile})`);

  for (let i = 0; i < 60; i++) {
    await sleep(500);
    const hostname = await metricsHostname(metrics);
    if (hostname) return { pid: child.pid, target: config.target, metrics, url: `https://${hostname}` };
    if (child.exitCode !== null) break;
  }
  throw new Error(`cloudflared didn't report a hostname in 30 s; see ${config.logFile}`);
}

export async function stopTunnel(pid) {
  try {
    process.kill(pid, "SIGTERM");
    log(`stopped cloudflared pid ${pid}`);
  } catch {
    // already gone
  }
}

// Reuse a running tunnel for the target (manual or ours) or start one (unless allowStart: false).
export async function ensureTunnel({ allowStart = true } = {}) {
  const tunnels = await findTunnels();
  const ours = tunnels.find((t) => t.url && t.metrics === `127.0.0.1:${config.metricsPort}`);
  const existing = ours || tunnels.find((t) => t.url);
  if (existing) return { ...existing, started: false };
  if (!allowStart) throw new Error(`no quick tunnel for ${config.target} is running`);
  return { ...(await startTunnel()), started: true };
}

// A fresh trycloudflare hostname can take a while to resolve; retry before giving up.
export async function waitForPublic(url, { attempts = 20, delayMs = 3000 } = {}) {
  for (let i = 1; i <= attempts; i++) {
    try {
      const res = await fetchWithTimeout(`${url}/`, 8000);
      await res.text();
      if (res.status === 200) return true;
      log(`public check ${i}/${attempts}: HTTP ${res.status}`);
    } catch (err) {
      log(`public check ${i}/${attempts}: ${err.cause?.code || err.message}`);
    }
    if (i < attempts) await sleep(delayMs);
  }
  return false;
}

// ---------- redirect repo ----------

async function git(args, opts = {}) {
  const { stdout } = await run("git", ["-C", config.redirectDir, ...args], {
    env: { ...process.env, GIT_TERMINAL_PROMPT: "0" }, // never hang on a credential prompt
    ...opts
  });
  return stdout.trim();
}

async function ensureRedirectRepo() {
  if (fs.existsSync(path.join(config.redirectDir, ".git"))) return;
  log(`cloning ${config.redirectRepo} → ${config.redirectDir}`);
  await run("git", ["clone", config.redirectRepo, config.redirectDir], {
    env: { ...process.env, GIT_TERMINAL_PROMPT: "0" }
  });
}

async function remoteHasBranch() {
  return Boolean(await git(["ls-remote", "--heads", "origin", config.redirectBranch]));
}

export function readPublishedUrl() {
  try {
    return parsePublishedUrl(fs.readFileSync(path.join(config.redirectDir, "_redirects"), "utf8"));
  } catch {
    return null;
  }
}

// Local commits not on origin yet (e.g. an earlier push failed). Uses the local remote ref only.
export async function hasUnpushedCommits() {
  try {
    if (!(await git(["rev-parse", "--verify", "-q", "HEAD"]).catch(() => ""))) return false;
    const upstream = `origin/${config.redirectBranch}`;
    if (!(await git(["rev-parse", "--verify", "-q", upstream]).catch(() => ""))) return true;
    return Number(await git(["rev-list", "--count", `${upstream}..HEAD`])) > 0;
  } catch {
    return false;
  }
}

// mkdir is atomic: keeps the watcher and a manual deploy from committing at the same time.
async function withLock(fn) {
  const lock = path.join(config.redirectDir, ".git", "tylertube-publish.lock");
  for (let i = 0; ; i++) {
    try {
      fs.mkdirSync(lock);
      break;
    } catch (err) {
      if (err.code !== "EEXIST") throw err;
      const age = Date.now() - fs.statSync(lock).mtimeMs;
      if (age > 120_000) fs.rmSync(lock, { recursive: true, force: true });
      else if (i > 60) throw new Error(`redirect repo locked (${lock})`);
      else await sleep(1000);
    }
  }
  try {
    return await fn();
  } finally {
    fs.rmSync(lock, { recursive: true, force: true });
  }
}

// Point the redirect repo at `url` and push. Returns "unchanged" | "pushed" | "dry-run".
export async function publishRedirect(url, { dryRun = false } = {}) {
  await ensureRedirectRepo();
  return withLock(async () => {
    const hasRemote = await remoteHasBranch();
    if (hasRemote) {
      await git(["fetch", "origin", config.redirectBranch]);
      // Keep a local commit whose push failed earlier; otherwise follow the remote.
      if (await hasUnpushedCommits()) await git(["rebase", "-q", `origin/${config.redirectBranch}`]);
      else await git(["checkout", "-q", "-B", config.redirectBranch, `origin/${config.redirectBranch}`]);
    } else {
      await git(["checkout", "-B", config.redirectBranch]).catch(() => {});
    }

    const files = { _redirects: renderRedirects(url), "index.html": renderIndexHtml(url) };
    const previous = {};
    for (const [name, content] of Object.entries(files)) {
      const file = path.join(config.redirectDir, name);
      previous[name] = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
      fs.writeFileSync(file, content);
    }
    await git(["add", "-A"]);
    if (!(await git(["status", "--porcelain"]))) {
      if (dryRun || !(await hasUnpushedCommits())) return "unchanged";
      await git(["push", "-q", "-u", "origin", config.redirectBranch]);
      return "pushed";
    }

    if (dryRun) {
      log(`dry run: would commit and push:\n${await git(["diff", "--cached", "--stat"])}`);
      await git(["reset", "-q"]);
      for (const [name, content] of Object.entries(previous)) {
        const file = path.join(config.redirectDir, name);
        if (content === null) fs.rmSync(file, { force: true });
        else fs.writeFileSync(file, content);
      }
      return "dry-run";
    }
    await git(["commit", "-q", "-m", `Point redirect at ${url}`]);
    await git(["push", "-q", "-u", "origin", config.redirectBranch]);
    return "pushed";
  });
}

// ---------- shared flow ----------

// Find/start the tunnel, then publish it if the redirect points elsewhere.
// quiet: say nothing when the tunnel is reused and the redirect is already current (watcher).
export async function ensureAndPublish({ dryRun = false, quiet = false } = {}) {
  const tunnel = await ensureTunnel({ allowStart: !dryRun });
  const published = readPublishedUrl();
  const current = published === tunnel.url && !(await hasUnpushedCommits());
  if (!(quiet && current && !tunnel.started)) {
    log(`${tunnel.started ? "new" : "existing"} tunnel ${tunnel.url} (pid ${tunnel.pid})`);
  }
  if (current) {
    if (!quiet) log("redirect already points there");
    return { tunnel, result: "unchanged" };
  }
  if (!(await waitForPublic(tunnel.url))) {
    log("tunnel URL isn't answering yet; publishing anyway");
  }
  const result = await publishRedirect(tunnel.url, { dryRun });
  log(`redirect ${result === "pushed" ? "pushed →" : result + ":"} ${tunnel.url}`);
  return { tunnel, result };
}

export function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

// ---------- CLI ----------

if (process.argv[1] && import.meta.url === pathToFileURL(fs.realpathSync(process.argv[1])).href) {
  const [cmd = "status"] = process.argv.slice(2);
  const dryRun = process.argv.includes("--dry-run");
  try {
    if (cmd === "status") {
      const tunnels = await findTunnels();
      console.log(`target:    ${config.target}`);
      for (const t of tunnels) console.log(`tunnel:    pid ${t.pid}  ${t.url || "(no hostname)"}  metrics ${t.metrics || "?"}`);
      if (!tunnels.length) console.log("tunnel:    none");
      console.log(`published: ${readPublishedUrl() || "(nothing yet)"}`);
    } else if (cmd === "ensure") {
      await ensureAndPublish({ dryRun });
    } else {
      console.error("usage: node scripts/tunnel.mjs status | ensure [--dry-run]");
      process.exit(2);
    }
  } catch (err) {
    console.error(`[tunnel] ${err.stderr?.trim() || err.message}`);
    process.exit(1);
  }
}
